#!/usr/bin/env python3
"""
Sync course PDFs from content/ to the shared Google Drive folder (Tops_Academy_Content)
and regenerate platform/src/data/pdfLinks.ts.

Usage:
  python scripts/sync_drive_pdfs.py           # Sync PDFs referenced by courses/*.json (+ existing Drive files)
  python scripts/sync_drive_pdfs.py --all     # Sync ALL PDFs under content/
  python scripts/sync_drive_pdfs.py --dry-run # Preview without uploading or writing
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

DRIVE_FOLDER_ID = "1WWEJOoa6kPPq3D2EgkiK7bi5kWAfwLKd"
REPO_ROOT = Path(__file__).resolve().parent.parent
CONTENT_DIR = REPO_ROOT / "content"
COURSES_DIR = REPO_ROOT / "courses"
PDF_LINKS_TS = REPO_ROOT / "platform" / "src" / "data" / "pdfLinks.ts"


def find_gdrive_cmd() -> str:
    cmd = shutil.which("gdrive")
    if cmd:
        return cmd
    fallback = Path.home() / ".gemini" / "config" / "plugins" / "gdrive" / "skills" / "gdrive" / "scripts" / "gdrive.cmd"
    if fallback.exists():
        return str(fallback)
    raise RuntimeError("Could not find 'gdrive' CLI on PATH.")


def run_gdrive(args: list[str]) -> str:
    cmd = [find_gdrive_cmd(), *args]
    res = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        raise RuntimeError(
            f"gdrive command failed ({' '.join(args)}):\n{res.stderr.strip() or res.stdout.strip()}"
        )
    return res.stdout


def list_drive_files(folder_id: str) -> dict[str, dict]:
    raw = run_gdrive(["readonly", "ls", folder_id, "--json"])
    items = json.loads(raw) if raw.strip() else []
    return {item["name"]: item for item in items if item.get("name")}


def collect_referenced_pdfs() -> set[str]:
    docs: set[str] = set()
    for path in sorted(glob.glob(str(COURSES_DIR / "*.json"))):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        for comp in data.get("competencies", []):
            for ev in comp.get("evidence", []):
                if ev.get("doc"):
                    docs.add(Path(ev["doc"]).name)
        for mod in data.get("modules", []):
            if mod.get("source_file"):
                docs.add(Path(mod["source_file"]).name)
    return docs


def index_local_pdfs() -> dict[str, Path]:
    found: dict[str, Path] = {}
    for pdf_path in sorted(CONTENT_DIR.rglob("*.pdf")):
        found.setdefault(pdf_path.name, pdf_path)
    return found


def write_pdf_links_ts(drive_files: dict[str, dict]) -> None:
    lines = [
        "/**",
        " * Maps PDF filenames (from course `evidence[].doc` or `module.source_file`)",
        " * to their publicly shared Google Drive viewer URLs.",
        " * Auto-generated by scripts/sync_drive_pdfs.py",
        " */",
        "export const PDF_LINKS: Record<string, string> = {",
    ]
    for name in sorted(drive_files):
        item = drive_files[name]
        if item.get("mimeType") != "application/pdf" and not name.lower().endswith(".pdf"):
            continue
        file_id = item["id"]
        escaped_name = name.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{escaped_name}':")
        lines.append(f"    'https://drive.google.com/file/d/{file_id}/view',")
    lines.extend([
        "};",
        "",
        "/**",
        " * Resolves a document filename or relative path to its public PDF URL, if available.",
        " */",
        "export function getPdfUrl(doc?: string | null): string | null {",
        "  if (!doc) return null;",
        "  const trimmed = doc.trim();",
        "  if (PDF_LINKS[trimmed]) return PDF_LINKS[trimmed];",
        "  const baseName = trimmed.split(/[/\\\\]/).pop();",
        "  return baseName && PDF_LINKS[baseName] ? PDF_LINKS[baseName] : null;",
        "}",
        "",
    ])
    PDF_LINKS_TS.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync content/ PDFs to Google Drive and update pdfLinks.ts")
    parser.add_argument("--all", action="store_true", help="Sync all PDFs under content/ instead of only course-referenced ones")
    parser.add_argument("--dry-run", action="store_true", help="Show planned actions without modifying Drive or files")
    args = parser.parse_args()

    local_pdfs = index_local_pdfs()
    drive_files = list_drive_files(DRIVE_FOLDER_ID)

    if args.all:
        targets = sorted(local_pdfs.keys())
    else:
        referenced = collect_referenced_pdfs() | set(drive_files.keys())
        targets = sorted(name for name in referenced if name in local_pdfs)

    uploaded = 0
    updated = 0
    skipped = 0

    for name in targets:
        local_path = local_pdfs[name]
        local_size = local_path.stat().st_size
        remote = drive_files.get(name)

        if not remote:
            print(f"[UPLOAD] {name} ({local_size} bytes)")
            if not args.dry_run:
                run_gdrive(["mutate", "upload", str(local_path), "--parent", DRIVE_FOLDER_ID])
            uploaded += 1
        else:
            remote_size = int(remote.get("size", -1))
            if remote_size != local_size:
                print(f"[UPDATE] {name} (remote={remote_size} -> local={local_size} bytes)")
                if not args.dry_run:
                    run_gdrive(["mutate", "update", remote["id"], str(local_path)])
                updated += 1
            else:
                skipped += 1

    if not args.dry_run:
        drive_files = list_drive_files(DRIVE_FOLDER_ID)
        write_pdf_links_ts(drive_files)
        print(f"Updated {PDF_LINKS_TS.relative_to(REPO_ROOT)} ({len(drive_files)} entries)")

    print(f"Summary: {uploaded} uploaded, {updated} updated, {skipped} already in sync.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
